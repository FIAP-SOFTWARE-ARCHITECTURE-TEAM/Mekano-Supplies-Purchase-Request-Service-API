CREATE TABLE requisicoes_compra (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL,
    status VARCHAR(30) NOT NULL,
    motivo VARCHAR(30) NOT NULL,
    observacao VARCHAR(255),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    CONSTRAINT ux_requisicoes_compra_uuid UNIQUE (uuid),
    CONSTRAINT ck_requisicoes_compra_status CHECK (status IN ('ABERTA', 'ENVIADA', 'COMPRA_APROVADA', 'PRODUTO_RECEBIDO', 'CANCELADA')),
    CONSTRAINT ck_requisicoes_compra_motivo CHECK (motivo IN ('ESTOQUE_MINIMO', 'ORDEM_SERVICO'))
);

CREATE INDEX ix_requisicoes_compra_status ON requisicoes_compra (status);
CREATE INDEX ix_requisicoes_compra_motivo ON requisicoes_compra (motivo);
CREATE INDEX ix_requisicoes_compra_created_at ON requisicoes_compra (created_at);
