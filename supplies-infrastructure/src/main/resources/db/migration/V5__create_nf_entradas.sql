CREATE TABLE nf_entradas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL,
    requisicao_uuid UUID NOT NULL,
    chave_acesso CHAR(44) NOT NULL,
    valor_total NUMERIC(12, 2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ATIVA',
    motivo_cancelamento VARCHAR(255),
    data_cancelamento TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    CONSTRAINT ux_nf_entradas_uuid UNIQUE (uuid),
    CONSTRAINT ux_nf_entradas_chave_acesso UNIQUE (chave_acesso),
    CONSTRAINT fk_nf_entradas_requisicao FOREIGN KEY (requisicao_uuid) REFERENCES requisicoes_compra (uuid),
    CONSTRAINT ck_nf_entradas_status CHECK (status IN ('ATIVA', 'CANCELADA')),
    CONSTRAINT ck_nf_entradas_valor_total CHECK (valor_total > 0)
);

CREATE INDEX ix_nf_entradas_requisicao ON nf_entradas (requisicao_uuid);
CREATE INDEX ix_nf_entradas_status ON nf_entradas (status);
