CREATE TABLE movimentos_estoque (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL,
    peca_uuid UUID NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    quantidade BIGINT NOT NULL,
    saldo_atual_apos BIGINT NOT NULL,
    saldo_reservado_apos BIGINT NOT NULL,
    origem VARCHAR(40) NOT NULL,
    referencia_uuid UUID,
    idempotency_key VARCHAR(200) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    created_by VARCHAR(100),
    CONSTRAINT ux_movimentos_estoque_uuid UNIQUE (uuid),
    CONSTRAINT ux_movimentos_estoque_idempotency UNIQUE (idempotency_key),
    CONSTRAINT ck_movimentos_estoque_tipo CHECK (tipo IN ('CREDITO', 'DEBITO', 'RESERVA', 'LIBERACAO', 'CONSUMO')),
    CONSTRAINT ck_movimentos_estoque_origem CHECK (origem IN (
        'NF_ENTRADA', 'NF_ENTRADA_CANCELAMENTO', 'REQUISICAO_COMPRA', 'SEED', 'AJUSTE', 'EXTERNO')),
    CONSTRAINT ck_movimentos_estoque_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_movimentos_estoque_saldo_atual CHECK (saldo_atual_apos >= 0),
    CONSTRAINT ck_movimentos_estoque_saldo_reservado CHECK (saldo_reservado_apos >= 0)
);

CREATE INDEX ix_movimentos_estoque_peca ON movimentos_estoque (peca_uuid);
CREATE INDEX ix_movimentos_estoque_created_at ON movimentos_estoque (created_at);
