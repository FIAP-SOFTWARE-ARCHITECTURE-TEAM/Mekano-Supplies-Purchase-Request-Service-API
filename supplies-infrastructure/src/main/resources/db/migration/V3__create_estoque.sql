CREATE TABLE estoque (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL,
    peca_uuid UUID NOT NULL,
    saldo_atual BIGINT NOT NULL DEFAULT 0,
    saldo_reservado BIGINT NOT NULL DEFAULT 0,
    estoque_minimo BIGINT,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    CONSTRAINT ux_estoque_uuid UNIQUE (uuid),
    CONSTRAINT ux_estoque_peca_uuid UNIQUE (peca_uuid),
    CONSTRAINT ck_estoque_saldo_atual CHECK (saldo_atual >= 0),
    CONSTRAINT ck_estoque_saldo_reservado CHECK (saldo_reservado >= 0),
    CONSTRAINT ck_estoque_minimo CHECK (estoque_minimo IS NULL OR estoque_minimo >= 0),
    CONSTRAINT ck_estoque_version CHECK (version >= 0)
);

CREATE INDEX ix_estoque_abaixo_minimo ON estoque (estoque_minimo);
