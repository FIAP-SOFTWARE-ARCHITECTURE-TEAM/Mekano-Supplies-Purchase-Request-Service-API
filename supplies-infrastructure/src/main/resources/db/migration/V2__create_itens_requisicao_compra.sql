CREATE TABLE itens_requisicao_compra (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL,
    requisicao_uuid UUID NOT NULL,
    peca_uuid UUID NOT NULL,
    peca_codigo VARCHAR(50) NOT NULL,
    peca_descricao VARCHAR(255) NOT NULL,
    quantidade BIGINT NOT NULL,
    valor_unitario NUMERIC(12, 2) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    created_by VARCHAR(100),
    CONSTRAINT fk_itens_requisicao_requisicao FOREIGN KEY (requisicao_uuid) REFERENCES requisicoes_compra (uuid),
    CONSTRAINT ck_itens_requisicao_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_itens_requisicao_valor_unitario CHECK (valor_unitario > 0)
);

CREATE UNIQUE INDEX ux_itens_requisicao_uuid ON itens_requisicao_compra (uuid);
CREATE UNIQUE INDEX ux_itens_requisicao_peca ON itens_requisicao_compra (requisicao_uuid, peca_uuid);
CREATE INDEX ix_itens_requisicao_peca_uuid ON itens_requisicao_compra (peca_uuid);
